let currentLanguage = 'en';

function setLanguage(lang) {
    if (translations[lang]) {
        currentLanguage = lang;
        localStorage.setItem('nutriscan_language', lang);
        updateUILanguage();
        showToast(`Language changed to ${getLanguageName(lang)}`, 'success');
    }
}

function getLanguageName(lang) {
    const names = { en: 'English', hi: 'हिन्दी', mr: 'मराठी', kn: 'ಕನ್ನಡ' };
    return names[lang] || 'English';
}

function t(key) {
    return translations[currentLanguage]?.[key] || translations.en[key] || key;
}

function updateUILanguage() {
    document.querySelectorAll('[data-i18n]').forEach(element => {
        if (element.closest('.auth-container')) {
            return;
        }
        const key = element.getAttribute('data-i18n');
        if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
            if (element.placeholder !== undefined) {
                element.placeholder = t(key);
            }
        } else {
            element.textContent = t(key);
        }
    });
    
    const langBtn = document.getElementById('languageBtn');
    if (langBtn) {
        const span = langBtn.querySelector('span');
        if (span) span.textContent = getLanguageName(currentLanguage);
    }
}

function loadSavedLanguage() {
    const savedLang = localStorage.getItem('nutriscan_language');
    if (savedLang && translations[savedLang]) {
        currentLanguage = savedLang;
    }
    updateUILanguage();
}

function translateAISummary(score, harmfulIngredients, alternatives) {
    let summary = '';
    
    if (score >= 7) {
        summary = t('aiResponseHealthy').replace('{score}', score);
    } else if (score >= 4) {
        summary = t('aiResponseModerate').replace('{score}', score);
    } else {
        summary = t('aiResponseUnhealthy').replace('{score}', score);
    }
    
    const harmfulText = harmfulIngredients.length > 0 
        ? t('aiResponseHarmful').replace('{ingredients}', harmfulIngredients.join(', '))
        : '';
    
    const alternativesText = alternatives && alternatives.length > 0
        ? t('aiResponseAlternatives').replace('{alternatives}', alternatives.slice(0, 3).join(', '))
        : '';
    
    return {
        summary: summary,
        harmful: harmfulText,
        alternatives: alternativesText
    };
}